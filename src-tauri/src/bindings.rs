fn render_events(cfg: &Config) -> String {
    format!(
        "/** App-wide events and their payloads. */\nexport interface Events {{\n  \"{GAME_EXITED}\": {};\n}}\n",
        LaunchOutcomeDto::name(cfg)
    )
}

fn render_commands(specs: &[CommandSpec]) -> String {
    let mut out = String::from(
        "/** Every backend command: its arguments and its success result. */\nexport interface Commands {\n",
    );
    for spec in specs {
        let args = if spec.args.is_empty() {
            "Record<string, never>".to_owned()
        } else {
            let fields: Vec<String> = spec
                .args
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect();
            format!("{{ {} }}", fields.join("; "))
        };
        out.push_str(&format!(
            "  {}: {{ args: {args}; result: {} }};\n",
            spec.name, spec.result
        ));
    }
    out.push_str("}\n");
    out
}

/// Renders the full contents of `src/ipc/bindings.ts`.
pub fn render() -> String {
    let cfg = Config::new();
    let mut output = String::from(HEADER);
    for declaration in declarations(&cfg) {
        output.push('\n');
        output.push_str("export ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output.push('\n');
    output.push_str(&render_commands(&commands(&cfg)));
    output.push('\n');
    output.push_str(&render_events(&cfg));
    output
}

