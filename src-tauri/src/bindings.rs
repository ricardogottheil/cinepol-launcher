fn render_events(cfg: &Config) -> String {
    format!(
        "/** App-wide events and their payloads. */\nexport interface Events {{\n  \"{GAME_EXITED}\": {};\n}}\n",
        LaunchOutcomeDto::name(cfg)
    )
}

fn render_commands(specs: &[CommandSpec]) -> String {
    let mut out = String::from(
        "/** Every backend command: its arguments and its success result. */\nexport interface Commands {\n",
    );
    for spec in specs {
        let args = if spec.args.is_empty() {
            "Record<string, never>".to_owned()
        } else {
            let fields: Vec<String> = spec
                .args
                .iter()
                .map(|(name, ty)| format!("{name}: {ty}"))
                .collect();
            format!("{{ {} }}", fields.join("; "))
        };
        out.push_str(&format!(
            "  {}: {{ args: {args}; result: {} }};\n",
            spec.name, spec.result
        ));
    }
    out.push_str("}\n");
    out
}

/// Renders the full contents of `src/ipc/bindings.ts`.
pub fn render() -> String {
    let cfg = Config::new();
    let mut output = String::from(HEADER);
    for declaration in declarations(&cfg) {
        output.push('\n');
        output.push_str("export ");
        output.push_str(&declaration);
        output.push('\n');
    }
    output.push('\n');
    output.push_str(&render_commands(&commands(&cfg)));
    output.push('\n');
    output.push_str(&render_events(&cfg));
    output
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    #[test]
    fn rendered_bindings_start_with_generated_header() {
        assert!(render().starts_with("// This file is GENERATED"));
    }

    #[test]
    fn exports_every_registered_command() {
        let rendered = render();
        for name in [
            "get_app_info",
            "run_progress_demo",
            "cancel_operation",
            "list_accounts",
            "create_offline_account",
            "check_premium_name",
            "get_account_policy",
            "login_microsoft",
            "remove_account",
            "get_account_skin",
            "set_active_account",
            "list_game_versions",
            "list_loader_versions",
            "list_instances",
            "create_instance",
            "install_instance",
            "launch_instance",
            "kill_instance",
            "get_server_config",
            "get_server_status",
            "play_on_cinepol",
            "get_settings",
            "set_server_config_url",
        ] {
            assert!(
                rendered.contains(&format!("  {name}: {{ args:")),
                "{name} missing"
            );
        }
    }

    #[test]
    fn bindings_file_is_up_to_date() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/ipc/bindings.ts");
        let on_disk = std::fs::read_to_string(path).unwrap();
        assert!(
            on_disk == render(),
            "src/ipc/bindings.ts is stale: run `pnpm bindings`"
        );
    }
}
